//! A tiny 5x7 block font covering only the characters the smoke test prints.
//!
//! Each glyph is seven rows, top to bottom; in each row bit 4 is the leftmost pixel and bit 0 the rightmost.

pub const GLYPH_W: usize = 5;
pub const GLYPH_H: usize = 7;

/// Returns the glyph for `c`, or `None` if the font does not cover it. Space is an empty glyph.
pub fn glyph(c: char) -> Option<[u8; GLYPH_H]> {
    Some(match c {
        ' ' => [0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00],
        'A' => [0x0E, 0x11, 0x11, 0x1F, 0x11, 0x11, 0x11],
        'B' => [0x1E, 0x11, 0x11, 0x1E, 0x11, 0x11, 0x1E],
        'C' => [0x0F, 0x10, 0x10, 0x10, 0x10, 0x10, 0x0F],
        'D' => [0x1E, 0x11, 0x11, 0x11, 0x11, 0x11, 0x1E],
        'E' => [0x1F, 0x10, 0x10, 0x1E, 0x10, 0x10, 0x1F],
        'H' => [0x11, 0x11, 0x11, 0x1F, 0x11, 0x11, 0x11],
        'I' => [0x0E, 0x04, 0x04, 0x04, 0x04, 0x04, 0x0E],
        'K' => [0x11, 0x12, 0x14, 0x18, 0x14, 0x12, 0x11],
        'L' => [0x10, 0x10, 0x10, 0x10, 0x10, 0x10, 0x1F],
        'M' => [0x11, 0x1B, 0x15, 0x15, 0x11, 0x11, 0x11],
        'N' => [0x11, 0x11, 0x19, 0x15, 0x13, 0x11, 0x11],
        'O' => [0x0E, 0x11, 0x11, 0x11, 0x11, 0x11, 0x0E],
        'P' => [0x1E, 0x11, 0x11, 0x1E, 0x10, 0x10, 0x10],
        'R' => [0x1E, 0x11, 0x11, 0x1E, 0x14, 0x12, 0x11],
        'S' => [0x0F, 0x10, 0x10, 0x0E, 0x01, 0x01, 0x1E],
        'T' => [0x1F, 0x04, 0x04, 0x04, 0x04, 0x04, 0x04],
        'U' => [0x11, 0x11, 0x11, 0x11, 0x11, 0x11, 0x0E],
        'V' => [0x11, 0x11, 0x11, 0x11, 0x11, 0x0A, 0x04],
        'W' => [0x11, 0x11, 0x11, 0x15, 0x15, 0x1B, 0x11],
        'X' => [0x11, 0x11, 0x0A, 0x04, 0x0A, 0x11, 0x11],
        'Y' => [0x11, 0x11, 0x0A, 0x04, 0x04, 0x04, 0x04],
        'l' => [0x0C, 0x04, 0x04, 0x04, 0x04, 0x04, 0x0E],
        'y' => [0x00, 0x11, 0x11, 0x11, 0x0F, 0x01, 0x0E],
        '0' => [0x0E, 0x11, 0x13, 0x15, 0x19, 0x11, 0x0E],
        '1' => [0x04, 0x0C, 0x04, 0x04, 0x04, 0x04, 0x0E],
        '3' => [0x1E, 0x01, 0x01, 0x0E, 0x01, 0x01, 0x1E],
        '+' => [0x00, 0x04, 0x04, 0x1F, 0x04, 0x04, 0x00],
        '.' => [0x00, 0x00, 0x00, 0x00, 0x00, 0x0C, 0x0C],
        '-' => [0x00, 0x00, 0x00, 0x0E, 0x00, 0x00, 0x00],
        _ => return None,
    })
}

/// Horizontal runs of lit pixels in one glyph row, as `(first_column, length)`. Drawing runs instead of single
/// pixels keeps the vertex count down.
pub fn row_runs(row: u8) -> impl Iterator<Item = (usize, usize)> {
    let mut col = 0;
    core::iter::from_fn(move || {
        while col < GLYPH_W && row & (0x10 >> col) == 0 {
            col += 1;
        }
        if col >= GLYPH_W {
            return None;
        }
        let start = col;
        while col < GLYPH_W && row & (0x10 >> col) != 0 {
            col += 1;
        }
        Some((start, col - start))
    })
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn runs_of_full_and_split_rows() {
        assert_eq!(row_runs(0x1F).collect::<Vec<_>>(), vec![(0, 5)]);
        assert_eq!(row_runs(0x11).collect::<Vec<_>>(), vec![(0, 1), (4, 1)]);
        assert_eq!(row_runs(0x0E).collect::<Vec<_>>(), vec![(1, 3)]);
        assert_eq!(row_runs(0x00).count(), 0);
    }

    #[test]
    fn glyphs_fit_in_five_bits() {
        for c in " ABCDEHIKLMNOPRSTUVWXYly013+.-".chars() {
            let g = glyph(c).expect("covered");
            assert!(g.iter().all(|r| r & !0x1F == 0), "{c}");
        }
        assert!(glyph('?').is_none());
    }
}
