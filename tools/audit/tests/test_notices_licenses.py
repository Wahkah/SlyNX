"""Notices check and the cargo-deny wrapper."""
import sys

from conftest import needs_git, write

from slynx_audit import licenses, notices
from slynx_audit.common import FAIL, publishable_files

LOCK = '''# This file is automatically @generated by Cargo.
version = 4

[[package]]
name = "slynx-engine"
version = "0.0.1"
dependencies = [
 "bitflags",
]

[[package]]
name = "bitflags"
version = "2.6.0"
source = "registry+https://github.com/rust-lang/crates.io-index"
checksum = "0000"

[[package]]
name = "glam"
version = "0.29.0"
source = "registry+https://github.com/rust-lang/crates.io-index"
'''


def test_lock_parsing_separates_our_crates():
    pk = notices.lock_packages(LOCK)
    assert [(n, bool(s)) for n, _, s in pk] == [('slynx-engine', False), ('bitflags', True), ('glam', True)]


def test_name_matching_is_whole_word():
    assert notices.mentioned('glam', '| glam | 0.29 | MIT OR Apache-2.0 |')
    assert notices.mentioned('glam', '`glam`')
    assert not notices.mentioned('glam', 'glamour')
    assert not notices.mentioned('serde', 'serde_json')


@needs_git
def test_missing_crates_fail(repo):
    write(repo, 'Cargo.lock', LOCK)
    write(repo, 'THIRD_PARTY_NOTICES.md', '# Notices\n\n## bitflags 2.6.0\nMIT OR Apache-2.0\n')
    r = notices.run(str(repo), publishable_files(str(repo)))
    assert r.status == FAIL
    assert [f.key for f in r.findings] == ['glam']


@needs_git
def test_complete_notices_pass_and_no_lock_passes(repo):
    write(repo, 'THIRD_PARTY_NOTICES.md', 'bitflags, glam\n')
    assert notices.run(str(repo), publishable_files(str(repo))).status == 'PASS'
    write(repo, 'Cargo.lock', LOCK)
    assert notices.run(str(repo), publishable_files(str(repo))).status == 'PASS'


@needs_git
def test_lock_without_notices_file_fails(repo):
    write(repo, 'Cargo.lock', LOCK)
    r = notices.run(str(repo), publishable_files(str(repo)))
    assert r.status == FAIL and r.findings[0].key == 'missing'


def fake_cargo_deny(tmp_path, code):
    script = write(tmp_path, f'deny{code}.py', f'import sys\nprint("checked", sys.argv[1:])\nsys.exit({code})\n')
    return [sys.executable, str(script)]


def test_licenses_skip_without_crates_or_tool(tmp_path):
    write(tmp_path, 'Cargo.toml', '[workspace]\nmembers = []\n')
    assert licenses.run(str(tmp_path), [], command=fake_cargo_deny(tmp_path, 1)).status == 'SKIP'
    write(tmp_path, 'Cargo.toml', '[workspace]\nmembers = ["crates/a"]\n')
    r = licenses.run(str(tmp_path), [], command=[])
    assert r.status == 'SKIP' and 'not installed' in r.summary


def test_licenses_pass_and_fail_follow_cargo_deny(tmp_path):
    write(tmp_path, 'Cargo.toml', '[workspace]\nmembers = ["crates/a"]\n')
    assert licenses.run(str(tmp_path), [], command=fake_cargo_deny(tmp_path, 0)).status == 'PASS'
    r = licenses.run(str(tmp_path), [], command=fake_cargo_deny(tmp_path, 1))
    assert r.status == FAIL
    assert any('licenses' in d for d in r.findings[0].details)
